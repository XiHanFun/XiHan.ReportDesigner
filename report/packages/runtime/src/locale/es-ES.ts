/** 问题参数里的名字写成 «名字»，前面带一个空格；没有时为空串。 */
function quoted(value: unknown): string {
  return value === undefined || value === null ? '' : ` «${String(value)}»`
}

/** 类型名：可以是 a|b 写法的几种之一。 */
function typeName(value: unknown): string {
  return String(value).split('|').map(item => TYPE_NAMES[item] ?? item).join(' o ')
}

function operatorName(value: unknown): string {
  return OPERATOR_NAMES[String(value)] ?? String(value)
}

/** 选项的名字，如聚合方式；不在对照表里的原样写出。 */
function optionName(value: unknown): string {
  return (OPTION_LABELS as Readonly<Record<string, string | undefined>>)[String(value)] ?? String(value)
}

/** 取值范围：min、max 与 exclusiveMin。 */
function range(params: Readonly<Record<string, unknown>>): string {
  const parts = [
    params.min === undefined ? undefined : `como mínimo ${String(params.min)}`,
    params.exclusiveMin === undefined ? undefined : `mayor que ${String(params.exclusiveMin)}`,
    params.max === undefined ? undefined : `como máximo ${String(params.max)}`,
  ].filter(part => part !== undefined)
  return parts.length === 0 ? '' : `; debe ser ${parts.join(' y ')}`
}

